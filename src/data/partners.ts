function hashId(id: string): number {
  let h = 0;
  for (let i = 0; i < id.length; i++) h = (h * 31 + id.charCodeAt(i)) >>> 0;
  return h;
}

/** Resolve campus photos for a partner (explicit list or stable placeholders). */
export function getPartnerPhotos(partner: Partner, count = 3): string[] {
  if (partner.photos?.length) return partner.photos.slice(0, Math.max(count, partner.photos.length));
  const start = hashId(partner.id) % CAMPUS_PHOTO_POOL.length;
  return Array.from({ length: count }, (_, i) => {
    return CAMPUS_PHOTO_POOL[(start + i * 3) % CAMPUS_PHOTO_POOL.length];
  });
}

